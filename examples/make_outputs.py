"""Regenerate the committed example outputs from examples/tank_farm.dxf.

    python examples/make_example.py     # the drawing
    python examples/make_outputs.py     # takeoff.xlsx, takeoff.json, csv/, docs/example-output.md

Runs from any folder; all paths in the outputs are relative.
"""

from __future__ import annotations

import contextlib
import io
import os
from pathlib import Path

from dxf_takeoff.cli import main

ROOT = Path(__file__).resolve().parent.parent
ARGS = ["examples/tank_farm.dxf", "--out-units", "m", "--group-by-attrib", "SIZE", "--rules", "examples/takeoff.toml"]


def run(args: list[str]) -> str:
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        code = main(args)
    if code:
        raise SystemExit(code)
    return buffer.getvalue()


if __name__ == "__main__":
    os.chdir(ROOT)
    run(ARGS + ["--xlsx", "examples/takeoff.xlsx", "--csv", "examples/csv", "--json", "examples/takeoff.json", "-q"])
    table = run(ARGS)
    command = "dxf-takeoff " + " ".join(f'"{a}"' if " " in a else a for a in ARGS)
    page = f"""---
title: Example output
description: Real dxf-takeoff output for the tank-farm piping example - lengths by layer, areas, valves by SIZE, BOQ.
---

# Example output

Real output of dxf-takeoff for [`examples/tank_farm.dxf`](https://github.com/Shahnawaz75/dxf-takeoff/blob/main/examples/tank_farm.dxf)
with the rules in [`examples/takeoff.toml`](https://github.com/Shahnawaz75/dxf-takeoff/blob/main/examples/takeoff.toml).
The drawing is generated by `examples/make_example.py`, which also computes the main
quantities by hand; the test suite checks that both agree to 12 significant digits.

```console
$ {command}
{table.rstrip()}
```

The same run with `--xlsx examples/takeoff.xlsx --csv examples/csv --json examples/takeoff.json`
writes the Excel workbook, the CSV files and the JSON document that are committed next to the drawing.
"""
    (ROOT / "docs" / "example-output.md").write_text(page, encoding="utf-8")
    print(table)
